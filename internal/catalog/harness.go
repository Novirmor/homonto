package catalog

import (
	"bytes"
	"fmt"

	"github.com/Novirmor/homonto/internal/capability"
)

// HarnessReferencePath is the generated harness map in the shared knowledge
// skill. Doctrine names capabilities ("the native question dialog"); this
// file says what each one is on every harness the config targets, and which
// guarantees that harness enforces (ADR 0082, M4.2).
const HarnessReferencePath = "references/harness.md"

// HasHarnessReference reports whether a skill carries the harness map.
func HasHarnessReference(name string) bool { return name == SharedKnowledgeSkill }

var harnessTitles = map[string]string{"opencode": "OpenCode", "claude": "Claude Code"}

// RenderHarness renders the harness map for the given declarations, one
// section per harness, in order.
func RenderHarness(decls []capability.Declaration) []byte {
	if len(decls) == 0 {
		return nil
	}
	var b bytes.Buffer
	b.WriteString("<!-- Generated by homonto apply. Do not edit. -->\n\n# Harness map\n\n")
	b.WriteString("Doctrine names capabilities, not tools. Use the section for the harness you are running in. ")
	b.WriteString("`enforced` means the harness itself guarantees the behavior; `limited` means it does with the stated, accepted gap (ADR 0105); ")
	b.WriteString("`instruction-only` means only these instructions stand behind it, so follow them exactly. A capability not listed is unavailable on that harness.\n")
	for _, d := range decls {
		title := harnessTitles[d.Harness]
		if title == "" {
			title = d.Harness
		}
		fmt.Fprintf(&b, "\n## %s\n\nDeclared for %s %s; tier: %s.\n\n| Capability | Native form | Level |\n|---|---|---|\n", title, title, d.Version, d.Tier())
		for _, n := range capability.Vocabulary() {
			level, ok := d.Provides[n]
			if !ok {
				continue
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", n, d.Native[n], level)
		}
		var notes []capability.Name
		for _, n := range capability.Vocabulary() {
			if d.Limitations[n] != "" {
				notes = append(notes, n)
			}
		}
		if len(notes) > 0 {
			b.WriteString("\nLimitations:\n\n")
			for _, n := range notes {
				fmt.Fprintf(&b, "- `%s`: %s\n", n, d.Limitations[n])
			}
		}
	}
	return b.Bytes()
}

// SetHarnessReference sets the rendered harness map Materialize writes into
// the shared knowledge skill; nil writes none.
func (c *Catalog) SetHarnessReference(ref []byte) { c.harnessRef = ref }
