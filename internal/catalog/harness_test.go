package catalog

import (
	"io/fs"
	"regexp"
	"strings"
	"testing"

	embedded "github.com/Novirmor/homonto/catalog"
	"github.com/Novirmor/homonto/internal/capability"
)

// Doctrine names capabilities; only the generated harness map names a
// harness's tools (M4.2). This is the doc lint for that rule.
var harnessToolNames = regexp.MustCompile("`(question|todowrite|todoread|apply_patch|webfetch|AskUserQuestion)`|OpenCode's (built-in|native)|question tool|the `task` tool|child sessions?")

func TestDoctrineNamesCapabilitiesNotHarnessTools(t *testing.T) {
	for _, root := range []string{"skills", "subagents", "commands"} {
		err := fs.WalkDir(embedded.FS, root, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".md") {
				return err
			}
			data, err := fs.ReadFile(embedded.FS, path)
			if err != nil {
				return err
			}
			for n, line := range strings.Split(string(data), "\n") {
				if m := harnessToolNames.FindString(line); m != "" {
					t.Errorf("%s:%d names harness tool %q; name the capability and link the generated harness map", path, n+1, m)
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}

func TestRenderHarnessMapsEveryDeclaredCapability(t *testing.T) {
	ref := string(RenderHarness(capability.Declarations()))
	for _, want := range []string{
		"<!-- Generated by homonto apply. Do not edit. -->", "## OpenCode", "## Claude Code", "tier: workflow",
		"| `question-dialog` | the built-in `question` tool | enforced |",
		"| `question-dialog` | the `AskUserQuestion` tool | limited |",
		"`mcp__homonto__<tool>`", "Limitations:", "at most four questions",
	} {
		if !strings.Contains(ref, want) {
			t.Errorf("harness map lacks %q", want)
		}
	}
	if strings.Contains(ref[strings.Index(ref, "## Claude Code"):], "status-ui") {
		t.Error("a capability Claude Code does not declare must not be listed for it")
	}
	if RenderHarness(nil) != nil {
		t.Error("no declarations must render no map")
	}
}
